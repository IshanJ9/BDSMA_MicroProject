@st.cache_data(show_spinner=False)
def load_episodes(analytics_dir: str = str(DEFAULT_ANALYTICS_DIR)) -> pd.DataFrame:
    """Load consecutive pollution episodes with enriched station metadata."""
    path = Path(analytics_dir) / "episodes"
    cols = [
        "station_id", "parameter", "start_time", "end_time", "duration_hours",
        "average_concentration", "maximum_concentration", "elevated_observations"
    ]
    df = _read_parquet_safe(path, cols)
    if not df.empty:
        df["start_time"] = pd.to_datetime(df["start_time"], errors="coerce")
        df["end_time"] = pd.to_datetime(df["end_time"], errors="coerce")

        # Enrich episodes with station names and locations from station_summary
        summary = load_station_summary(analytics_dir)
        if not summary.empty:
            st_info = summary[["station_id", "station_name", "city", "state"]].drop_duplicates(subset=["station_id"])
            df = df.merge(st_info, on="station_id", how="left")
            df["station_name"] = df["station_name"].fillna(df["station_id"])
            df["city"] = df["city"].fillna("Unknown")
            df["state"] = df["state"].fillna("Unknown")
    return df


@st.cache_data(show_spinner=False)
def load_spatial_hotspots(analytics_dir: str = str(DEFAULT_ANALYTICS_DIR)) -> pd.DataFrame:
    """Load coordinate-validated spatial station summaries with hotspot attributes."""
    path = Path(analytics_dir) / "spatial_hotspots"
    cols = [
        "station_id", "station_name", "city", "state", "parameter", "coord_source",
        "latitude", "longitude", "mean_concentration", "max_concentration",
        "min_concentration", "stddev_concentration", "observation_count",
        "classification", "persistence_score", "coverage_sufficient",
        "grid_latitude", "grid_longitude"
    ]
    df = _read_parquet_safe(path, cols)
    if not df.empty:
        # Drop rows with null coordinates for mapping
        df = df.dropna(subset=["latitude", "longitude"]).copy()
        df["latitude"] = pd.to_numeric(df["latitude"], errors="coerce")
        df["longitude"] = pd.to_numeric(df["longitude"], errors="coerce")
    return df


