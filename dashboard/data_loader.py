def _read_parquet_safe(dir_or_file: Path | str, fallback_columns: list[str] | None = None) -> pd.DataFrame:
    """Read a Parquet directory or file safely, returning an empty DataFrame if missing or empty."""
    target = Path(dir_or_file)
    if not target.exists():
        logger.warning("Parquet path does not exist: %s", target)
        return pd.DataFrame(columns=fallback_columns or [])

    try:
        # Check if directory contains any parquet files
        if target.is_dir():
            parquet_files = list(target.glob("*.parquet")) + list(target.glob("**/*.parquet"))
            if not parquet_files:
                logger.warning("No parquet part files found in: %s", target)
                return pd.DataFrame(columns=fallback_columns or [])
            # Read directory directly using pyarrow engine
            df = pd.read_parquet(target, engine="pyarrow")
        else:
            df = pd.read_parquet(target, engine="pyarrow")

        return df
    except Exception as e:
        logger.error("Error reading Parquet from %s: %s", target, e)
        return pd.DataFrame(columns=fallback_columns or [])


def check_analytics_status(analytics_dir: Path | str = DEFAULT_ANALYTICS_DIR) -> dict[str, bool]:
    """Check whether each analytical Parquet output exists on disk."""
    root = Path(analytics_dir)
    status = {}
    for name in EXPECTED_OUTPUTS:
        path = root / name
        has_parquet = False
        if path.is_dir():
            has_parquet = any(path.glob("*.parquet")) or (path / "_SUCCESS").exists()
        status[name] = has_parquet
    return status


@st.cache_data(show_spinner=False)
def load_temporal_data(analytics_dir: str = str(DEFAULT_ANALYTICS_DIR)) -> pd.DataFrame:
    """Load temporal analytics (hourly, daily, monthly, weekday/weekend)."""
    path = Path(analytics_dir) / "temporal"
    cols = [
        "temporal_granularity", "parameter", "period", "mean_concentration",
        "max_concentration", "min_concentration", "stddev_concentration",
        "observation_count", "period_z_score", "is_unusually_elevated"
    ]
    df = _read_parquet_safe(path, cols)
    if not df.empty and "period" in df.columns:
        # Convert daily period to string for uniform processing
        df["period"] = df["period"].astype(str)
    return df


@st.cache_data(show_spinner=False)
def load_station_summary(analytics_dir: str = str(DEFAULT_ANALYTICS_DIR)) -> pd.DataFrame:
    """Load station-level concentration summary and coverage metrics."""
    path = Path(analytics_dir) / "station_summary"
    cols = [
        "station_id", "station_name", "city", "state", "parameter",
        "mean_concentration", "max_concentration", "min_concentration",
        "stddev_concentration", "observation_count", "first_observation",
        "last_observation", "active_days"
    ]
    df = _read_parquet_safe(path, cols)
    if not df.empty:
        if "first_observation" in df.columns:
            df["first_observation"] = pd.to_datetime(df["first_observation"], errors="coerce")
        if "last_observation" in df.columns:
            df["last_observation"] = pd.to_datetime(df["last_observation"], errors="coerce")
    return df


