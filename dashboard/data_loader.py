def get_available_pollutants(data: dict[str, pd.DataFrame]) -> list[str]:
    """Extract list of available pollutants across loaded datasets."""
    found: set[str] = set()
    for key in ["temporal", "station_summary", "hotspots"]:
        df = data.get(key)
        if df is not None and not df.empty and "parameter" in df.columns:
            found.update(df["parameter"].dropna().unique().tolist())
    if not found:
        return POLLUTANTS
    # Preserve preferred project order
    return [p for p in POLLUTANTS if p in found] or sorted(found)


def get_available_states(data: dict[str, pd.DataFrame]) -> list[str]:
    """Extract list of available states."""
    summary = data.get("station_summary")
    if summary is not None and not summary.empty and "state" in summary.columns:
        states = sorted([s for s in summary["state"].dropna().unique().tolist() if s.strip()])
        return ["All States"] + states
    return ["All States"]


def get_available_cities(data: dict[str, pd.DataFrame], state: str | None = None) -> list[str]:
    """Extract list of available cities, optionally filtered by state."""
    summary = data.get("station_summary")
    if summary is not None and not summary.empty and "city" in summary.columns:
        df = summary
        if state and state != "All States" and "state" in df.columns:
            df = df[df["state"] == state]
        cities = sorted([c for c in df["city"].dropna().unique().tolist() if c.strip()])
        return ["All Cities"] + cities
    return ["All Cities"]


def compute_executive_kpis(
    data: dict[str, pd.DataFrame],
    pollutant: str,
    state: str | None = None,
    city: str | None = None,
) -> dict[str, Any]:
    """Calculate executive KPI values from real project analytics data."""
    summary_df = data.get("station_summary", pd.DataFrame())
    hotspots_df = data.get("hotspots", pd.DataFrame())
    episodes_df = data.get("episodes", pd.DataFrame())

    # Apply filters
    def apply_filters(df: pd.DataFrame) -> pd.DataFrame:
        if df.empty:
            return df
        d = df
        if "parameter" in d.columns:
            d = d[d["parameter"] == pollutant]
        if state and state != "All States" and "state" in d.columns:
            d = d[d["state"] == state]
        if city and city != "All Cities" and "city" in d.columns:
            d = d[d["city"] == city]
        return d

    filtered_summary = apply_filters(summary_df)
    filtered_hotspots = apply_filters(hotspots_df)
    filtered_episodes = apply_filters(episodes_df)

    stations_count = len(filtered_summary["station_id"].unique()) if not filtered_summary.empty else 0
    total_observations = int(filtered_summary["observation_count"].sum()) if (
        not filtered_summary.empty and "observation_count" in filtered_summary.columns
    ) else 0

    mean_conc = (
        filtered_summary["mean_concentration"].mean()
        if not filtered_summary.empty and "mean_concentration" in filtered_summary.columns
        else None
    )
    max_conc = (
        filtered_summary["max_concentration"].max()
        if not filtered_summary.empty and "max_concentration" in filtered_summary.columns
        else None
    )

    hotspot_count = 0
    if not filtered_hotspots.empty and "classification" in filtered_hotspots.columns:
        hotspot_count = int(
            filtered_hotspots["classification"].isin(["persistent_hotspot", "frequently_elevated"]).sum()
        )

    episode_count = len(filtered_episodes) if not filtered_episodes.empty else 0

    return {
        "pollutant": pollutant,
        "stations_count": stations_count,
        "total_observations": total_observations,
        "mean_concentration": mean_conc,
        "max_concentration": max_conc,
        "hotspot_count": hotspot_count,
        "episode_count": episode_count,
        "threshold": get_threshold(pollutant),
    }
